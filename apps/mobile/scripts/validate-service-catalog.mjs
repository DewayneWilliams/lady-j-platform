import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const manifestUrl = new URL("../supabase/catalog/lady_j_services.json", import.meta.url);
const intakeUrl = new URL("../supabase/catalog/lady_j_service_intake.sql", import.meta.url);
const catalog = JSON.parse(readFileSync(manifestUrl, "utf8"));
const expectedCategories = [
  "Specials",
  "Hair",
  "Nails",
  "Lashes",
  "Brows",
  "Waxing",
  "Facials",
  "Skin Treatments",
  "Makeup",
  "Body Treatments",
  "Massage",
  "Foot Health",
  "Barbering",
];
assert.deepEqual(catalog.category_order, expectedCategories);
assert.equal(typeof catalog.source_complete, "boolean");
assert.equal(catalog.entries.length, 129, "The complete supplied menu contains 129 entries.");
assert.deepEqual(
  expectedCategories.map(
    (category) => catalog.entries.filter((entry) => entry.category === category).length,
  ),
  [0, 23, 25, 7, 11, 17, 14, 8, 5, 5, 11, 1, 2],
);
const seen = new Set();
const categoryState = new Map();
let complete = 0;
let unknownDurations = 0;
let licensedImages = 0;
let addons = 0;
for (const entry of catalog.entries) {
  assert.ok(expectedCategories.includes(entry.category), entry.name);
  assert.ok(catalog.supplied_categories.includes(entry.category), entry.name);
  assert.notEqual(entry.category, "Specials", "Imported offers must never be invented.");
  assert.equal(entry.status, "draft", "Intake entries cannot be published.");
  const sourceKey = createHash("sha256")
    .update(`${entry.category}|${entry.name}`)
    .digest("hex")
    .slice(0, 24);
  assert.equal(entry.source_key, sourceKey, entry.name);
  assert.ok(!seen.has(sourceKey), `Duplicate: ${entry.name}`);
  seen.add(sourceKey);
  const previous = categoryState.get(entry.category) ?? { order: 0, addon: false };
  assert.equal(entry.sort_order, previous.order + 1, entry.name);
  assert.ok(!previous.addon || entry.is_add_on, `Primary service after add-ons: ${entry.name}`);
  categoryState.set(entry.category, { order: entry.sort_order, addon: entry.is_add_on });
  assert.equal(typeof entry.is_add_on, "boolean");
  if (entry.is_add_on) addons++;
  const hours = entry.duration_label.match(/(\d+) hours?/);
  const minutes = entry.duration_label.match(/(\d+) mins/);
  const duration =
    hours || minutes ? Number(hours?.[1] ?? 0) * 60 + Number(minutes?.[1] ?? 0) : null;
  assert.equal(entry.duration_minutes, duration, entry.name);
  if (duration === null) {
    unknownDurations++;
    assert.ok(["Varies", "N/A"].includes(entry.duration_label), entry.name);
  } else {
    assert.ok(Number.isInteger(duration) && duration > 0 && duration <= 480, entry.name);
  }
  if (entry.price_label === null || entry.price_label === "N/A") {
    assert.equal(entry.price_amount, null, entry.name);
    assert.equal(entry.price_kind, null, entry.name);
    assert.equal(entry.price_unit, null, entry.name);
  } else {
    assert.match(entry.price_label, /^(From )?\$[\d,]+(?:\/(?:nail|toe|couple))?$/, entry.name);
    assert.equal(
      entry.price_amount,
      Number(entry.price_label.match(/\$([\d,]+)/)[1].replaceAll(",", "")),
      entry.name,
    );
    const unit = entry.price_label.includes("/") ? entry.price_label.split("/")[1] : null;
    assert.equal(entry.price_unit, unit, entry.name);
    assert.equal(
      entry.price_kind,
      entry.price_label.startsWith("From ") ? "from" : unit ? "per_item" : "fixed",
      entry.name,
    );
  }
  assert.ok(typeof entry.description === "string" && entry.description.length > 0, entry.name);
  if (entry.description && entry.price_amount !== null) complete++;
  if (entry.image !== null) {
    assert.ok(
      entry.image_license?.source_url &&
        entry.image_license?.license_url &&
        entry.image_license?.author,
      entry.name,
    );
    licensedImages++;
  } else {
    assert.equal(entry.image_license, null, entry.name);
  }
  assert.ok(
    entry.compatible_service_keys === null ||
      entry.compatible_service_keys.every((key) =>
        catalog.entries.some((candidate) => candidate.source_key === key),
      ),
    entry.name,
  );
}

// This intake is separate from lj_services: no active menu, appointments, payments,
// clients, receipts, RLS policies or booking RPCs are replaced by this statement.
const literal = (value) => `'${value.replaceAll("'", "''")}'`;
const values = catalog.entries
  .map(
    (entry) =>
      `(${literal(catalog.catalog_key)}, ${literal(entry.source_key)}, ${literal(JSON.stringify(entry))}::jsonb)`,
  )
  .join(",\n");
const sql = `-- GENERATED by scripts/validate-service-catalog.mjs --write-intake.
-- Pending source intake only. Apply only after confirming draftbit-dev-1.
-- Full supplied source, including incomplete Makeup drafts. No active services are changed.
begin;
create table if not exists public.lj_service_catalog_intake (
  catalog_key text not null,
  source_key text not null,
  source_entry jsonb not null,
  primary key (catalog_key, source_key),
  check (coalesce(source_entry->>'source_key' = source_key, false)),
  check (coalesce(source_entry->>'status' = 'draft', false))
);
alter table public.lj_service_catalog_intake enable row level security;
revoke all on public.lj_service_catalog_intake from public, anon, authenticated;
grant select on public.lj_service_catalog_intake to authenticated;
grant all on public.lj_service_catalog_intake to service_role;
drop policy if exists lj_catalog_intake_owner_read on public.lj_service_catalog_intake;
create policy lj_catalog_intake_owner_read on public.lj_service_catalog_intake
  for select to authenticated using (public.lj_is_owner());
insert into public.lj_service_catalog_intake (catalog_key, source_key, source_entry) values
${values}
on conflict (catalog_key, source_key) do update
  set source_entry = excluded.source_entry;
commit;
`;
if (process.argv.includes("--write-intake")) writeFileSync(intakeUrl, sql);
else
  assert.equal(readFileSync(intakeUrl, "utf8"), sql, "Intake SQL must match the validated source.");
console.log(
  JSON.stringify(
    {
      complete_entries: complete,
      incomplete_entries: catalog.entries.length - complete,
      total_entries: catalog.entries.length,
      primary_complete: complete - addons,
      addons,
      unknown_durations: unknownDurations,
      licensed_images: licensedImages,
      source_complete: catalog.source_complete,
      offline_validation: true,
    },
    null,
    2,
  ),
);
if (process.argv.includes("--require-ready")) {
  assert.ok(catalog.source_complete, "The catalog source is truncated.");
  assert.equal(complete, catalog.entries.length, "Incomplete entries remain.");
  assert.equal(licensedImages, catalog.entries.length, "Licensed image coverage is incomplete.");
  assert.equal(unknownDurations, 0, "Unknown durations require an owner-defined quoting workflow.");
  assert.ok(
    !catalog.entries.some((entry) => entry.is_add_on && !entry.compatible_service_keys?.length),
    "Add-on compatibility must be defined before booking.",
  );
}
